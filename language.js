/* =========================================================
   2. STATE BAHASA
   ========================================================= */
let currentLang = "id";

/* Ambil bahasa tersimpan, jika ada */
(function initLang() {
  try {
    const saved = localStorage.getItem("pangan-lokal-lang");
    if (saved === "id" || saved === "en") {
      currentLang = saved;
    }
  } catch (e) {
    /* localStorage tidak tersedia — abaikan */
  }
})();


/* =========================================================
   3. FUNGSI UTAMA
   ========================================================= */

/**
 * Ambil terjemahan berdasarkan key.
 * Mendukung placeholder {n}, {name}, dsb.
 * Contoh: t("products.count", { n: 20 })
 */
function t(key, vars) {
  const dict = translations[currentLang] || translations.id;
  let text = dict[key];

  /* Fallback ke ID jika key tidak ditemukan */
  if (text === undefined) {
    text = translations.id[key] !== undefined ? translations.id[key] : key;
  }

  /* Ganti placeholder */
  if (vars && typeof vars === "object") {
    Object.keys(vars).forEach(function (k) {
      text = text.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
    });
  }

  return text;
}

/**
 * Terapkan terjemahan ke seluruh elemen dengan atribut:
 * - data-i18n            → mengubah textContent
 * - data-i18n-placeholder → mengubah placeholder
 * - data-i18n-aria       → mengubah aria-label
 */
function applyTranslations() {
  /* text content */
  const elements = document.querySelectorAll("[data-i18n]");
  elements.forEach(function (el) {
    const key = el.getAttribute("data-i18n");
    el.textContent = t(key);
  });

  /* placeholder */
  const placeholders = document.querySelectorAll("[data-i18n-placeholder]");
  placeholders.forEach(function (el) {
    const key = el.getAttribute("data-i18n-placeholder");
    el.setAttribute("placeholder", t(key));
  });

  /* aria-label */
  const arias = document.querySelectorAll("[data-i18n-aria]");
  arias.forEach(function (el) {
    const key = el.getAttribute("data-i18n-aria");
    el.setAttribute("aria-label", t(key));
  });

  /* Update atribut lang di <html> */
  document.documentElement.setAttribute("lang", currentLang);
}

/**
 * Ganti bahasa.
 */
function setLanguage(lang) {
  if (lang !== "id" && lang !== "en") return;
  currentLang = lang;

  try {
    localStorage.setItem("pangan-lokal-lang", lang);
  } catch (e) {
    /* abaikan */
  }

  /* Update label tombol bahasa */
  const langCurrent = document.getElementById("langCurrent");
  if (langCurrent) {
    langCurrent.textContent = lang.toUpperCase();
  }

  /* Update judul tombol (aria-label) */
  const langToggle = document.getElementById("langToggle");
  if (langToggle) {
    langToggle.setAttribute("aria-label", t("ui.langSwitch"));
  }

  /* Terapkan ke DOM */
  applyTranslations();

  /* Beri tahu app.js bahwa bahasa berubah (re-render konten dinamis) */
  if (typeof window.onLanguageChange === "function") {
    window.onLanguageChange(lang);
  }
}

/**
 * Toggle bahasa ID ↔ EN.
 */
function toggleLanguage() {
  setLanguage(currentLang === "id" ? "en" : "id");
}

/**
 * Ambil bahasa saat ini.
 */
function getCurrentLang() {
  return currentLang;
}


/* =========================================================
   4. INISIALISASI OTOMATIS
   ========================================================= */
document.addEventListener("DOMContentLoaded", function () {
  /* Set label tombol bahasa */
  const langCurrent = document.getElementById("langCurrent");
  if (langCurrent) {
    langCurrent.textContent = currentLang.toUpperCase();
  }

  /* Terapkan terjemahan ke seluruh halaman */
  applyTranslations();

  /* Pasang event ke tombol bahasa */
  const langToggle = document.getElementById("langToggle");
  if (langToggle) {
    langToggle.addEventListener("click", toggleLanguage);
  }
});


/* =========================================================
   5. EKSPOR KE GLOBAL (untuk dipakai app.js)
   ========================================================= */
window.translations    = translations;
window.t               = t;
window.applyTranslations = applyTranslations;
window.setLanguage     = setLanguage;
window.toggleLanguage  = toggleLanguage;
window.getCurrentLang  = getCurrentLang;


